#!/usr/bin/env python3
"""Assemble the nvidia-runai Blueprint YAMLs, one per variant, from shared sources.

blueprint.base.yaml holds everything except component values and overlays.
For each component, values/<chartName>.yaml becomes its `values`, and the files
under overlays/<chartName>/ become `kustomize: {dir: overlay, files: ...}`.

Each variants/<variant>.yaml is a flat list of `key: value` or `key: |` blocks:
- `<chartName>.fields` and `<chartName>.values` are YAML added to that component's
  fields and values. They may only add keys, never replace one.
- Every other key is a variable. `{{key}}` in the base, values/, overlays/ and other
  variables is replaced by its value; a line holding only `{{key}}` takes a multi-line
  value, indented like the placeholder, or disappears if the value is `""`. Unknown
  placeholders and unused variables fail.
- displayName and version are required. name (the displayName slug) and crName
  (the metadata.name convention) are derived, and name-version.yaml is the output.

A published Blueprint never changes: once name-version.yaml is on the base branch,
CI (.github/workflows/ci-charts.yml) fails if it is changed, renamed or deleted. Bump
`version` in the variant instead; that writes a new file and leaves the old one as is.

Usage: build.py [--check]   (--check exits 1 with a diff if an output is stale)
"""
import argparse
import difflib
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "..", "files", "blueprints")
HEADER = ("# Generated by charts/aif-operator/blueprint-src/nvidia-runai/build.py.\n"
          "# Do not edit; change the sources there and run build.py.\n")

ITEM = re.compile(r"^  - chartName: (\S+)\s*$")
PLAIN_KEY = re.compile(r"^[A-Za-z0-9._/-]+$")
KEY_LINE = re.compile(r"""^( *)("[^"]+"|'[^']+'|[A-Za-z0-9._/-]+):(?: +(.*))?$""")
VARIANT_LINE = re.compile(r"^([A-Za-z0-9._-]+):(?: +(.*))?$")
PLACEHOLDER = re.compile(r"\{\{([A-Za-z][A-Za-z0-9]*)\}\}")
ADDITION = re.compile(r"^(.+)\.(fields|values)$")
FIELD = "    "


class BuildError(Exception):
    pass


def read(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    if "\r" in text:
        raise BuildError(f"{path}: carriage returns are not supported")
    return text


def indent_lines(text, prefix):
    return [prefix + line if line else "" for line in text.split("\n")]


def block_scalar(key, text, indent):
    if text == "":
        return [f'{indent}{key}: ""']
    if not text.endswith("\n"):
        chomp = "-"
    elif text.endswith("\n\n"):
        chomp = "+"
    else:
        chomp = ""
    first = next((line for line in text.split("\n") if line), "")
    hint = "2" if first.startswith(" ") else ""
    body = text[:-1] if text.endswith("\n") else text
    return [f"{indent}{key}: |{hint}{chomp}"] + indent_lines(body, indent + "  ")


def yaml_key(key):
    return key if PLAIN_KEY.match(key) else json.dumps(key)


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def parse_variant(text, where):
    out, key, block = {}, None, None
    for n, line in enumerate(text.split("\n"), 1):
        if block is not None and (line.startswith("  ") or not line.strip()):
            block.append(line[2:])
            continue
        if block is not None:
            out[key] = "\n".join(block).rstrip("\n") + "\n"
            block = None
        if not line.strip() or line.startswith("#"):
            continue
        m = VARIANT_LINE.match(line)
        if not m or m.group(1) in out:
            raise BuildError(f"{where}:{n}: expected a new 'key: value' or 'key: |' (got {line!r})")
        key = m.group(1)
        if m.group(2) == "|":
            block = []
        elif m.group(2) == '""':
            out[key] = ""
        elif m.group(2):
            out[key] = m.group(2)
        else:
            raise BuildError(f"{where}:{n}: {key} has no value")
    if block is not None:
        out[key] = "\n".join(block).rstrip("\n") + "\n"
    return out


def substitute(text, variables, used, where, expanding=()):
    def value(name):
        if name not in variables:
            raise BuildError(f"{where}: unknown variable {name!r}")
        if name in expanding:
            raise BuildError(f"{where}: variable {name!r} refers to itself")
        used.add(name)
        return substitute(variables[name], variables, used, where, expanding + (name,))

    def inline(m):
        v = value(m.group(1))
        if "\n" in v.rstrip("\n"):
            raise BuildError(f"{where}: multi-line variable {m.group(1)!r} must be alone on its line")
        return v.rstrip("\n")

    out = []
    for line in text.split("\n"):
        m = PLACEHOLDER.fullmatch(line.strip())
        if m:
            prefix = line[:len(line) - len(line.lstrip())]
            v = value(m.group(1)).rstrip("\n")
            out += indent_lines(v, prefix) if v else []
        else:
            out.append(PLACEHOLDER.sub(inline, line))
    return "\n".join(out)


def key_name(m):
    key = m.group(2)
    return key[1:-1] if key[0] in "\"'" else key


def indent_of(line):
    return len(line) - len(line.lstrip())


def key_blocks(lines, indent):
    """[key, start, end] for each key at `indent`; start includes the comments above it."""
    blocks, comments = [], None
    for i, line in enumerate(lines):
        m = KEY_LINE.match(line)
        if m and len(m.group(1)) == indent:
            start = i if comments is None else comments
            if blocks:
                blocks[-1][2] = start
            blocks.append([key_name(m), start, len(lines)])
            comments = None
        elif line.strip().startswith("#") and len(line) - len(line.lstrip()) == indent:
            comments = i if comments is None else comments
        else:
            comments = None
    return blocks


def addition_blocks(lines, indent, where):
    """key_blocks, but every line must belong to a key at `indent`: nothing is dropped."""
    blocks = key_blocks(lines, indent)
    first = blocks[0][1] if blocks else len(lines)
    stray = [line for line in lines[:first] if line.strip()]
    for _, start, end in blocks:
        head = header_index(lines, start)
        body = [line for line in lines[head + 1:end] if line.strip() and not line.lstrip().startswith("#")]
        floor = max(indent + 1, indent_of(body[0])) if body else 0
        stray += [line for line in body if indent_of(line) < floor]
    if stray:
        raise BuildError(f"{where}: {stray[0].strip()!r} is not under a key at indent {indent}")
    return blocks


def child_indent(lines, where):
    for line in lines:
        if line.strip() and not line.strip().startswith("#"):
            m = KEY_LINE.match(line)
            if not m:
                raise BuildError(f"{where}: only mappings can be merged into")
            return len(m.group(1))
    raise BuildError(f"{where}: empty mapping")


def header_index(lines, start):
    return next(i for i in range(start, len(lines)) if not lines[i].strip().startswith("#"))


def merge_additions(base, additions, where, indent=0, path=""):
    """Adds the keys in `additions` (YAML lines) to the mapping `base`; never replaces one."""
    base = list(base)
    for key, start, end in addition_blocks(additions, indent, f"{where}: {path or 'top level'}"):
        here = path + key
        add = additions[start:end]
        found = [b for b in key_blocks(base, indent) if b[0] == key]
        if not found:
            at = len(base)
            while at > 0 and not base[at - 1].strip():
                at -= 1
            base[at:at] = add
            continue
        if header_index(add, 0) != 0:
            raise BuildError(f"{where}: {here} exists; a comment can only precede a new key")
        _, bstart, bend = found[0]
        bhead = header_index(base, bstart)
        if KEY_LINE.match(add[0]).group(3) or KEY_LINE.match(base[bhead]).group(3):
            raise BuildError(f"{where}: {here} is already set; additions can't replace a value")
        sub_indent = child_indent(add[1:], f"{where}: {here}")
        if child_indent(base[bhead + 1:bend], f"{where}: {here} (base)") != sub_indent:
            raise BuildError(f"{where}: {here}: indent differs from the base")
        base[bhead + 1:bend] = merge_additions(base[bhead + 1:bend], add[1:], where, sub_indent, here + ".")
    return base


class Variant:
    def __init__(self, path):
        self.path = path
        entries = parse_variant(read(path), path)
        self.additions = {}
        self.variables = {}
        for key, value in entries.items():
            m = ADDITION.match(key)
            if m:
                self.additions[(m.group(1), m.group(2))] = value.rstrip("\n").split("\n")
            else:
                self.variables[key] = value
        for key in ("displayName", "version"):
            if key not in self.variables:
                raise BuildError(f"{path}: {key} is required")
        for key in ("name", "crName"):
            if key in self.variables:
                raise BuildError(f"{path}: {key} is derived from displayName and version; don't set it")
        name = slug(self.variables["displayName"])
        version = self.variables["version"]
        self.variables["name"] = name
        self.variables["crName"] = name + "-" + version.split("+")[0].replace(".", "-")
        self.output = os.path.join(OUT_DIR, f"{name}-{version}.yaml")
        self.used = set()

    def sub(self, text, where):
        return substitute(text, self.variables, self.used, where)

    def check_used(self, charts):
        unused = sorted(set(self.variables) - self.used - {"name", "crName"})
        if unused:
            raise BuildError(f"{self.path}: unused variables: {', '.join(unused)}")
        unknown = sorted(chart for chart, _ in self.additions if chart not in charts)
        if unknown:
            raise BuildError(f"{self.path}: additions for unknown components: {', '.join(unknown)}")


def values_lines(chart, variant):
    path = os.path.join(HERE, "values", f"{chart}.yaml")
    lines = []
    if os.path.exists(path):
        text = variant.sub(read(path), path).strip("\n")
        if not text or text.startswith("---"):
            raise BuildError(f"{path}: must be a single non-empty YAML mapping")
        lines = text.split("\n")
    added = variant.additions.get((chart, "values"))
    if added:
        lines = merge_additions(lines, added, f"{variant.path}: {chart}.values")
    if not lines:
        return []
    return [f"{FIELD}values:"] + indent_lines("\n".join(lines), FIELD + "  ")


def overlay_lines(chart, variant):
    root = os.path.join(HERE, "overlays", chart)
    if not os.path.isdir(root):
        return []
    files = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and d != "__pycache__")
        for name in filenames:
            if name.startswith("."):
                continue
            rel = os.path.relpath(os.path.join(dirpath, name), root).replace(os.sep, "/")
            files.append(("overlay/" + rel, os.path.join(dirpath, name)))
    files.sort()
    if "overlay/kustomization.yaml" not in dict(files):
        raise BuildError(f"{root}: missing kustomization.yaml")
    lines = [f"{FIELD}kustomize:", f"{FIELD}  dir: overlay", f"{FIELD}  files:"]
    for key, path in files:
        lines += block_scalar(yaml_key(key), variant.sub(read(path), path), FIELD + "    ")
    return lines


def assemble_item(item, variant):
    chart = ITEM.match(item[0]).group(1)
    end = len(item)
    while end > 1 and (not item[end - 1].strip() or item[end - 1].lstrip().startswith("#")):
        end -= 1
    fields = item[1:end]
    added = variant.additions.get((chart, "fields"))
    if added:
        shallow = [line for line in fields if line.strip() and not line.startswith(FIELD)]
        if shallow:
            raise BuildError(f"component {chart}: {shallow[0].strip()!r} is indented less than its fields; "
                             f"move it to make room for {chart}.fields")
        dedented = [line[len(FIELD):] for line in fields]
        fields = [FIELD + line if line else "" for line in
                  merge_additions(dedented, added, f"{variant.path}: {chart}.fields")]
    for line in fields:
        if re.match(r"^    (values|kustomize):", line):
            raise BuildError(f"component {chart}: set {line.split(':')[0].strip()} in values/ or overlays/, "
                             f"or as {chart}.values in a variant")
    return [item[0]] + fields + values_lines(chart, variant) + overlay_lines(chart, variant) + item[end:]


def build(variant):
    base = os.path.join(HERE, "blueprint.base.yaml")
    lines = variant.sub(read(base), base).rstrip("\n").split("\n")
    try:
        start = lines.index("  components:") + 1
    except ValueError:
        raise BuildError("blueprint.base.yaml: spec.components not found")
    out = lines[:start]
    item = None
    charts = []
    for line in lines[start:]:
        if ITEM.match(line):
            if item:
                out += assemble_item(item, variant)
            item = [line]
            charts.append(ITEM.match(line).group(1))
        elif line.startswith(FIELD) or not line.strip() or line.startswith("  #"):
            if item is None:
                out.append(line)
            else:
                item.append(line)
        else:
            raise BuildError(f"blueprint.base.yaml: components must be the last key of spec "
                             f"and each item must start with '- chartName:' (got {line!r})")
    if item:
        out += assemble_item(item, variant)
    variant.check_used(charts)
    return HEADER + "\n".join(out) + "\n"


def variants():
    paths = sorted(glob.glob(os.path.join(HERE, "variants", "*.yaml")))
    if not paths:
        raise BuildError("no variants/*.yaml")
    found = [Variant(p) for p in paths]
    outputs = [v.output for v in found]
    if len(set(outputs)) != len(outputs):
        raise BuildError("two variants have the same name and version")
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail with a diff if an output is stale")
    args = parser.parse_args()
    try:
        built = [(v.output, build(v)) for v in variants()]
    except BuildError as e:
        print(f"build.py: {e}", file=sys.stderr)
        return 2
    stale = 0
    for path, text in built:
        rel = os.path.relpath(path, HERE)
        if args.check:
            current = read(path) if os.path.exists(path) else ""
            if current != text:
                sys.stdout.writelines(difflib.unified_diff(
                    current.splitlines(True), text.splitlines(True), rel + " (current)", rel + " (generated)"))
                print(f"{rel} is stale; run build.py", file=sys.stderr)
                stale = 1
            continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {rel}")
    return stale


if __name__ == "__main__":
    sys.exit(main())
